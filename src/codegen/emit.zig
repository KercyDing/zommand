const std = @import("std");
const schema = @import("schema");

/// Emits a typed CLI module from a schema.
pub fn emit(allocator: std.mem.Allocator, cli: schema.Cli, writer: *std.Io.Writer) !void {
    try validateCli(allocator, cli);

    try writer.writeAll(
        \\//! Generated by codegen from a .zon schema.
        \\//! DO NOT EDIT.
        \\
        \\const std = @import("std");
        \\const command = @import("command");
        \\
        \\
    );

    try writeGlobals(allocator, writer, cli);

    for (cli.commands) |command| {
        try writeCommandType(allocator, writer, command);
    }

    try writer.writeAll("/// Parsed result for the CLI commands.\n");
    try writer.writeAll("pub const Result = union(enum) {\n");
    for (cli.commands) |command| {
        const id = try resolveId(allocator, command.name);
        try writer.print("    {f}: {f},\n", .{
            std.zig.fmtId(id),
            std.zig.fmtId(try typeName(allocator, id)),
        });
    }
    try writer.writeAll("};\n\n");

    try writer.writeAll("const schema: command.Cli = .{\n");
    try writeField(writer, 1, "name", cli.name);
    try writeField(writer, 1, "version", cli.version);
    try writeOptionalField(writer, 1, "help", cli.help);
    try writeArgs(writer, 1, cli.args);
    try writer.writeAll("    .commands = &.{\n");
    for (cli.commands) |command| {
        try writeCommand(writer, command);
    }
    try writer.writeAll("    },\n};\n\n");

    try writer.writeAll(
        \\const Parser = command.Generate(schema, Globals, Result);
        \\
        \\// =============== Types ===============
        \\/// Result of a successful parse.
        \\pub const Parsed = Parser.Parsed;
        \\/// Parsing outcome, including help and version requests.
        \\pub const Outcome = Parser.Outcome;
        \\/// Errors returned when parsing process arguments fails.
        \\pub const ParseError = command.ParseError;
        \\
        \\// =============== Parsing ===============
        \\/// Parses process arguments, exiting with code 2 on usage errors and
        \\/// code 1 when the arguments cannot be read.
        \\pub fn parseOrExit(init: std.process.Init) Parsed {
        \\    return Parser.parseOrExit(init);
        \\}
        \\
        \\/// Parses an explicit argument slice, including the program name at
        \\/// index 0. Does not print diagnostics or exit.
        \\pub fn parseArgs(
        \\    arena: std.mem.Allocator,
        \\    argv: []const [:0]const u8,
        \\) ParseError!Outcome {
        \\    return Parser.parseArgs(arena, argv);
        \\}
        \\
        \\/// Releases slices allocated for repeated positional arguments and options.
        \\pub fn deinit(parsed: *Parsed, allocator: std.mem.Allocator) void {
        \\    Parser.deinit(parsed, allocator);
        \\}
        \\
    );
}

fn writeGlobals(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    cli: schema.Cli,
) !void {
    if (cli.args.len == 0) {
        try writer.writeAll("/// Program-level argument values.\npub const Globals = struct {};\n\n");
        return;
    }

    try writer.writeAll("/// Program-level argument values.\npub const Globals = struct {\n");
    for (cli.args) |arg| {
        try writer.print("    {f}: {s},\n", .{
            std.zig.fmtId(try resolveId(allocator, schema.argName(arg))),
            argType(arg),
        });
    }
    try writer.writeAll("};\n\n");
}

fn writeCommandType(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    command: schema.Command,
) !void {
    const id = try resolveId(allocator, command.name);
    const type_name = try typeName(allocator, id);

    if (command.args.len == 0) {
        try writer.print("pub const {f} = struct {{}};\n\n", .{
            std.zig.fmtId(type_name),
        });
        return;
    }

    try writer.print("pub const {f} = struct {{\n", .{
        std.zig.fmtId(type_name),
    });
    for (command.args) |arg| {
        try writer.print("    {f}: {s},\n", .{
            std.zig.fmtId(try resolveId(allocator, schema.argName(arg))),
            argType(arg),
        });
    }
    try writer.writeAll("};\n\n");
}

fn writeCommand(
    writer: *std.Io.Writer,
    command: schema.Command,
) !void {
    try writer.writeAll("        .{\n");
    try writeField(writer, 3, "name", command.name);
    try writeField(writer, 3, "help", command.help);
    try writeArgs(writer, 3, command.args);
    try writer.writeAll("        },\n");
}

fn writeArgs(writer: *std.Io.Writer, indent: usize, args: []const schema.Arg) !void {
    try writeIndent(writer, indent);
    if (args.len == 0) {
        try writer.writeAll(".args = &.{},\n");
        return;
    }
    try writer.writeAll(".args = &.{\n");
    for (args) |arg| try writeArg(writer, indent + 1, arg);
    try writeIndent(writer, indent);
    try writer.writeAll("},\n");
}

fn writeArg(writer: *std.Io.Writer, indent: usize, arg: schema.Arg) !void {
    try writeIndent(writer, indent);
    try writer.writeAll(".{\n");

    switch (arg) {
        .positional => |value| {
            try writeIndent(writer, indent + 1);
            try writer.writeAll(".positional = .{\n");
            try writeField(writer, indent + 2, "name", value.name);
            try writeOptionalField(writer, indent + 2, "placeholder", value.placeholder);
            try writeField(writer, indent + 2, "help", value.help);
            try writeBoolField(writer, indent + 2, "required", value.required);
            try writeBoolField(writer, indent + 2, "multiple", value.multiple);
        },
        .flag => |value| {
            try writeIndent(writer, indent + 1);
            try writer.writeAll(".flag = .{\n");
            try writeField(writer, indent + 2, "name", value.name);
            try writeOptionalField(writer, indent + 2, "short", value.short);
            try writeField(writer, indent + 2, "help", value.help);
        },
        .option => |value| {
            try writeIndent(writer, indent + 1);
            try writer.writeAll(".option = .{\n");
            try writeField(writer, indent + 2, "name", value.name);
            try writeOptionalField(writer, indent + 2, "short", value.short);
            try writeOptionalField(writer, indent + 2, "placeholder", value.placeholder);
            try writeField(writer, indent + 2, "help", value.help);
            try writeBoolField(writer, indent + 2, "required", value.required);
            try writeBoolField(writer, indent + 2, "multiple", value.multiple);
            try writeOptionalField(writer, indent + 2, "default", value.default);
        },
    }

    try writeIndent(writer, indent + 1);
    try writer.writeAll("},\n");
    try writeIndent(writer, indent);
    try writer.writeAll("},\n");
}

fn writeField(writer: *std.Io.Writer, indent: usize, name: []const u8, value: []const u8) !void {
    try writeIndent(writer, indent);
    try writer.print(".{s} = \"{f}\",\n", .{ name, std.zig.fmtString(value) });
}

fn writeOptionalField(
    writer: *std.Io.Writer,
    indent: usize,
    name: []const u8,
    value: ?[]const u8,
) !void {
    try writeIndent(writer, indent);
    if (value) |string| {
        try writer.print(".{s} = \"{f}\",\n", .{ name, std.zig.fmtString(string) });
    } else {
        try writer.print(".{s} = null,\n", .{name});
    }
}

fn writeBoolField(writer: *std.Io.Writer, indent: usize, name: []const u8, value: bool) !void {
    try writeIndent(writer, indent);
    try writer.print(".{s} = {},\n", .{ name, value });
}

fn writeIndent(writer: *std.Io.Writer, count: usize) !void {
    for (0..count) |_| try writer.writeAll("    ");
}

fn argType(arg: schema.Arg) []const u8 {
    return switch (arg) {
        .positional => |value| if (value.multiple)
            "[]const []const u8"
        else if (value.required)
            "[]const u8"
        else
            "?[]const u8",

        .flag => "bool",

        .option => |value| if (value.multiple)
            "[]const []const u8"
        else if (value.required or value.default != null)
            "[]const u8"
        else
            "?[]const u8",
    };
}

fn resolveId(
    allocator: std.mem.Allocator,
    name: []const u8,
) ![]const u8 {
    const buffer = try allocator.alloc(u8, name.len);
    defer allocator.free(buffer);

    const id = schema.deriveId(name, buffer) orelse {
        std.log.err(
            "name '{s}' is invalid: it must convert to a Zig identifier",
            .{name},
        );
        return error.InvalidSchema;
    };
    return allocator.dupe(u8, id);
}

fn typeName(allocator: std.mem.Allocator, id: []const u8) ![]const u8 {
    var result: std.ArrayList(u8) = .empty;
    errdefer result.deinit(allocator);

    var capitalize = true;
    for (id) |byte| {
        if (byte == '_') {
            capitalize = true;
            continue;
        }
        const output = if (capitalize) std.ascii.toUpper(byte) else byte;
        try result.append(allocator, output);
        capitalize = false;
    }

    const name = try result.toOwnedSlice(allocator);
    if (!std.zig.isValidId(name)) {
        std.log.err("cannot derive a valid type name from '{s}'", .{id});
        return error.InvalidSchema;
    }
    return name;
}

fn validateCli(allocator: std.mem.Allocator, cli: schema.Cli) !void {
    _ = std.SemanticVersion.parse(cli.version) catch {
        std.log.err("version '{s}' is not a valid semantic version", .{cli.version});
        return error.InvalidSchema;
    };

    if (cli.commands.len == 0) {
        std.log.err("CLI must contain at least one command", .{});
        return error.InvalidSchema;
    }

    try validateArgs(allocator, cli.args, "program", true);

    for (cli.commands, 0..) |command, index| {
        try validateCommandName(command.name);
        if (command.help.len == 0) {
            std.log.err("command '{s}' must have help text", .{command.name});
            return error.InvalidSchema;
        }
        const id = try resolveId(allocator, command.name);
        _ = try typeName(allocator, id);
        try validateArgs(allocator, command.args, command.name, false);

        for (cli.commands[0..index]) |previous| {
            if (std.mem.eql(u8, command.name, previous.name)) {
                std.log.err("duplicate command name '{s}'", .{command.name});
                return error.InvalidSchema;
            }

            const previous_id = try resolveId(allocator, previous.name);
            if (std.mem.eql(u8, id, previous_id)) {
                std.log.err(
                    "commands '{s}' and '{s}' derive the same field '{s}'",
                    .{ previous.name, command.name, id },
                );
                return error.InvalidSchema;
            }

            const name = try typeName(allocator, id);
            const previous_name = try typeName(allocator, previous_id);
            if (std.mem.eql(u8, name, previous_name)) {
                std.log.err(
                    "commands '{s}' and '{s}' derive the same type name '{s}'",
                    .{ command.name, previous.name, name },
                );
                return error.InvalidSchema;
            }
        }
    }

    for (cli.args) |global_arg| {
        for (cli.commands) |command| {
            for (command.args) |command_arg| {
                if (!isNamed(global_arg) or !isNamed(command_arg)) continue;

                if (std.mem.eql(
                    u8,
                    schema.argName(global_arg),
                    schema.argName(command_arg),
                )) {
                    std.log.err(
                        "program argument '--{s}' conflicts with command '{s}'",
                        .{ schema.argName(global_arg), command.name },
                    );
                    return error.InvalidSchema;
                }

                if (argShort(global_arg)) |global_short| {
                    if (argShort(command_arg)) |command_short| {
                        if (std.mem.eql(u8, global_short, command_short)) {
                            std.log.err(
                                "program argument '-{s}' conflicts with command '{s}'",
                                .{ global_short, command.name },
                            );
                            return error.InvalidSchema;
                        }
                    }
                }
            }
        }
    }
}

fn validateArgs(
    allocator: std.mem.Allocator,
    args: []const schema.Arg,
    owner: []const u8,
    is_program: bool,
) !void {
    var multiple_positional = false;
    var optional_positional = false;

    for (args, 0..) |arg, index| {
        const id = try resolveId(allocator, schema.argName(arg));
        const help = switch (arg) {
            .positional => |value| value.help,
            .flag => |value| value.help,
            .option => |value| value.help,
        };
        if (help.len == 0) {
            std.log.err(
                "argument '{s}' in '{s}' must have help text",
                .{ schema.argName(arg), owner },
            );
            return error.InvalidSchema;
        }

        switch (arg) {
            .positional => |value| {
                if (is_program) {
                    std.log.err("program-level arguments must be flags or options", .{});
                    return error.InvalidSchema;
                }
                if (multiple_positional) {
                    std.log.err(
                        "multiple positional argument must be the last positional argument",
                        .{},
                    );
                    return error.InvalidSchema;
                }
                if (value.required and optional_positional) {
                    std.log.err(
                        "required positional argument cannot follow an optional one",
                        .{},
                    );
                    return error.InvalidSchema;
                }
                if (!value.required) optional_positional = true;
                multiple_positional = value.multiple;
                if (value.placeholder) |name| try validateDisplayName(name, owner);
            },
            .flag => |value| {
                const long = value.name;
                try validateLongName(long, owner);
                if (std.mem.eql(u8, long, "help") or std.mem.eql(u8, long, "version")) {
                    std.log.err("argument name 'help' or 'version' is reserved", .{});
                    return error.InvalidSchema;
                }
                if (value.short) |short| try validateShort(short, owner);
            },
            .option => |value| {
                const long = value.name;
                try validateLongName(long, owner);
                if (std.mem.eql(u8, long, "help") or std.mem.eql(u8, long, "version")) {
                    std.log.err("argument name 'help' or 'version' is reserved", .{});
                    return error.InvalidSchema;
                }
                if (value.short) |short| try validateShort(short, owner);
                if (value.required and value.default != null) {
                    std.log.err(
                        "option '--{s}' cannot be required and have a default",
                        .{long},
                    );
                    return error.InvalidSchema;
                }
                if (value.multiple and value.default != null) {
                    std.log.err("multiple option cannot have a default value", .{});
                    return error.InvalidSchema;
                }
                if (value.placeholder) |name| try validateDisplayName(name, owner);
            },
        }

        for (args[0..index]) |previous| {
            const previous_id = try resolveId(allocator, schema.argName(previous));
            if (std.mem.eql(u8, id, previous_id)) {
                std.log.err(
                    "arguments '{s}' and '{s}' both derive field '{s}' in '{s}'",
                    .{ schema.argName(previous), schema.argName(arg), id, owner },
                );
                return error.InvalidSchema;
            }

            if (isNamed(arg) and isNamed(previous)) {
                if (std.mem.eql(u8, schema.argName(arg), schema.argName(previous))) {
                    std.log.err(
                        "duplicate argument name '--{s}' in '{s}'",
                        .{ schema.argName(arg), owner },
                    );
                    return error.InvalidSchema;
                }

                if (argShort(arg)) |short| {
                    if (argShort(previous)) |previous_short| {
                        if (std.mem.eql(u8, short, previous_short)) {
                            std.log.err(
                                "duplicate short argument '-{s}' in '{s}'",
                                .{ short, owner },
                            );
                            return error.InvalidSchema;
                        }
                    }
                }
            }
        }
    }
}

fn validateCommandName(name: []const u8) !void {
    if (!schema.isValidName(name)) {
        std.log.err("invalid command name '{s}'", .{name});
        return error.InvalidSchema;
    }
}

fn validateLongName(name: []const u8, owner: []const u8) !void {
    if (!schema.isValidName(name)) {
        std.log.err("invalid argument name '{s}' in '{s}'", .{ name, owner });
        return error.InvalidSchema;
    }
}

fn validateDisplayName(name: []const u8, owner: []const u8) !void {
    if (!schema.isValidDisplayName(name)) {
        std.log.err("invalid placeholder '{s}' in '{s}'", .{ name, owner });
        return error.InvalidSchema;
    }
}

fn validateShort(short: []const u8, owner: []const u8) !void {
    if (!schema.isValidShort(short)) {
        std.log.err("invalid short argument '{s}' in '{s}'", .{ short, owner });
        return error.InvalidSchema;
    }
}

fn isNamed(arg: schema.Arg) bool {
    return switch (arg) {
        .positional => false,
        .flag, .option => true,
    };
}

fn argShort(arg: schema.Arg) ?[]const u8 {
    return switch (arg) {
        .positional => null,
        .flag => |value| value.short,
        .option => |value| value.short,
    };
}
