const std = @import("std");
const schema = @import("schema");

pub fn emit(allocator: std.mem.Allocator, cli: schema.Cli, writer: *std.Io.Writer) !void {
    try writer.writeAll(
        \\// Generated by codegen from a .zon schema. Do not edit.
        \\const std = @import("std");
        \\const command = @import("command");
        \\
        \\
    );

    for (cli.commands) |command| {
        try writeCommandType(allocator, writer, command);
    }

    try writer.writeAll("pub const Result = union(enum) {\n");
    for (cli.commands) |command| {
        try writer.print("    {f}: {f},\n", .{
            std.zig.fmtId(command.name),
            std.zig.fmtId(try typeName(allocator, command.name)),
        });
    }
    try writer.writeAll("};\n\n");

    try writer.writeAll("const schema: command.Cli = .{\n");
    try writeField(writer, 1, "name", cli.name);
    try writeOptionalField(writer, 1, "version", cli.version);
    try writeField(writer, 1, "about", cli.about);
    try writeOptionalField(writer, 1, "long_about", cli.long_about);
    try writeArgs(writer, 1, cli.args);
    try writer.writeAll("    .commands = &.{\n");
    for (cli.commands) |command| try writeCommand(writer, command);
    try writer.writeAll("    },\n};\n\n");

    try writer.writeAll(
        \\const Parser = command.Generate(schema, Result);
        \\
        \\pub const ParseError = error{
        \\    OutOfMemory,
        \\    ArgumentsUnavailable,
        \\    CommandNotFound,
        \\    ArgumentNotFound,
        \\    MissingRequiredArgument,
        \\    MissingOptionValue,
        \\    TooManyArguments,
        \\};
        \\
        \\pub fn parse(
        \\    arena: std.mem.Allocator,
        \\    args: std.process.Args,
        \\) ParseError!Result {
        \\    return Parser.parse(arena, args);
        \\}
        \\
        \\pub fn deinit(result: *Result, allocator: std.mem.Allocator) void {
        \\    Parser.deinit(result, allocator);
        \\}
        \\
        \\pub fn programName() []const u8 {
        \\    return Parser.programName();
        \\}
        \\
    );
}

fn writeCommandType(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    command: schema.Command,
) !void {
    try validateIdentifier(command.name, "command name");
    try writer.print("pub const {f} = struct {{\n", .{
        std.zig.fmtId(try typeName(allocator, command.name)),
    });
    for (command.args) |arg| {
        const id = argId(arg);
        try validateIdentifier(id, "argument id");
        try writer.print("    {f}: {s},\n", .{
            std.zig.fmtId(id),
            typeString(arg),
        });
    }
    try writer.writeAll("};\n\n");
}

fn writeCommand(writer: *std.Io.Writer, command: schema.Command) !void {
    try writer.writeAll("        .{\n");
    try writeField(writer, 3, "name", command.name);
    try writeField(writer, 3, "about", command.about);
    try writeOptionalField(writer, 3, "long_about", command.long_about);
    try writeArgs(writer, 3, command.args);
    try writer.writeAll("        },\n");
}

fn writeArgs(writer: *std.Io.Writer, indent: usize, args: []const schema.Arg) !void {
    try writeIndent(writer, indent);
    if (args.len == 0) {
        try writer.writeAll(".args = &.{},\n");
        return;
    }
    try writer.writeAll(".args = &.{\n");
    for (args) |arg| try writeArg(writer, indent + 1, arg);
    try writeIndent(writer, indent);
    try writer.writeAll("},\n");
}

fn writeArg(writer: *std.Io.Writer, indent: usize, arg: schema.Arg) !void {
    try writeIndent(writer, indent);
    switch (arg) {
        .positional => |value| {
            try writer.writeAll(".{ .positional = .{\n");
            try writeField(writer, indent + 1, "id", value.id);
            try writeField(writer, indent + 1, "help", value.help);
            try writeBoolField(writer, indent + 1, "required", value.required);
            try writeBoolField(writer, indent + 1, "multiple", value.multiple);
        },
        .flag => |value| {
            try writer.writeAll(".{ .flag = .{\n");
            try writeField(writer, indent + 1, "id", value.id);
            try writeOptionalField(writer, indent + 1, "short", value.short);
            try writeField(writer, indent + 1, "help", value.help);
            try writeBoolField(writer, indent + 1, "global", value.global);
            try writeBoolField(writer, indent + 1, "multiple", value.multiple);
        },
        .option => |value| {
            try writer.writeAll(".{ .option = .{\n");
            try writeField(writer, indent + 1, "id", value.id);
            try writeOptionalField(writer, indent + 1, "short", value.short);
            try writeField(writer, indent + 1, "help", value.help);
            try writeBoolField(writer, indent + 1, "required", value.required);
            try writeBoolField(writer, indent + 1, "multiple", value.multiple);
            try writeOptionalField(writer, indent + 1, "default", value.default);
            try writeBoolField(writer, indent + 1, "global", value.global);
        },
    }
    try writeIndent(writer, indent);
    try writer.writeAll("} },\n");
}

fn writeField(writer: *std.Io.Writer, indent: usize, name: []const u8, value: []const u8) !void {
    try writeIndent(writer, indent);
    try writer.print(".{s} = \"{f}\",\n", .{ name, std.zig.fmtString(value) });
}

fn writeOptionalField(
    writer: *std.Io.Writer,
    indent: usize,
    name: []const u8,
    value: ?[]const u8,
) !void {
    try writeIndent(writer, indent);
    if (value) |string| {
        try writer.print(".{s} = \"{f}\",\n", .{ name, std.zig.fmtString(string) });
    } else {
        try writer.print(".{s} = null,\n", .{name});
    }
}

fn writeBoolField(writer: *std.Io.Writer, indent: usize, name: []const u8, value: bool) !void {
    try writeIndent(writer, indent);
    try writer.print(".{s} = {},\n", .{ name, value });
}

fn writeIndent(writer: *std.Io.Writer, count: usize) !void {
    for (0..count) |_| try writer.writeAll("    ");
}

fn typeName(allocator: std.mem.Allocator, name: []const u8) ![]const u8 {
    const result = try allocator.dupe(u8, name);
    if (result.len > 0) result[0] = std.ascii.toUpper(result[0]);
    return result;
}

fn typeString(arg: schema.Arg) []const u8 {
    return switch (arg) {
        .positional => |value| if (value.multiple)
            "[]const []const u8"
        else if (value.required)
            "[]const u8"
        else
            "?[]const u8",

        .flag => |value| if (value.multiple) "usize" else "bool",

        .option => |value| if (value.multiple)
            "[]const []const u8"
        else if (value.required or value.default != null)
            "[]const u8"
        else
            "?[]const u8",
    };
}

fn argId(arg: schema.Arg) []const u8 {
    return switch (arg) {
        .positional => |value| value.id,
        .flag => |value| value.id,
        .option => |value| value.id,
    };
}

fn validateIdentifier(name: []const u8, kind: []const u8) !void {
    if (!std.zig.isValidId(name)) {
        std.log.err("{s} must be a valid Zig identifier: '{s}'", .{ kind, name });
        return error.InvalidSchema;
    }
}
